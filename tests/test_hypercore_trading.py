@pytest.mark.parametrize("case", FIXTURES["fixtures"], ids=lambda c: c["name"])
def test_gateway_signer_reproduces_every_official_fixture(case):
    wire, nonce, expiry = case["action"], case["nonce"], case["expires_after"]
    assert "0x" + signing.action_hash(wire, nonce, expiry).hex() == case["action_hash"]
    assert "0x" + signing.digest(wire, nonce, expiry).hex() == case["digest"]
    signature = signing.sign(FIXTURES["key"], wire, nonce, expiry)
    assert signature.model_dump() == case["signature"]
    assert signing.recover(wire, nonce, expiry, signature) == FIXTURES["signer"].lower()


@pytest.mark.parametrize("case", FIXTURES["fixtures"], ids=lambda c: c["name"])
def test_model_verifier_reproduces_every_official_fixture(case):
    wire, nonce, expiry = case["action"], case["nonce"], case["expires_after"]
    assert pack(wire).hex() == case["msgpack"]
    assert "0x" + connection_id(wire, nonce, expiry).hex() == case["action_hash"]
    assert signer_of(wire, nonce, expiry, case["signature"]) == FIXTURES["signer"].lower()


