def request(nonce=T0, action=None):
    return signing.ActionRequest(
        action=action or signing.Noop(), nonce=nonce, expires_after=nonce + 30_000
    )


def test_verified_signer_recovers_the_agent_and_refuses_a_substitution(tmp_path):
    keys = LocalAgentKeys(tmp_path / "keys.json", "deployment")
    verified = VerifiedSigner(LocalSigner(keys), LocalSigner(keys).address)
    agent = verified.generate_hyperliquid_agent(SAFE)
    assert verified.hyperliquid_agents(SAFE, frozenset({agent})) == {agent}
    signed = verified.sign_hyperliquid_action(SAFE, agent, request())
    assert signed.agent == agent and json.loads(signed.body())["vaultAddress"] is None
    assert json.loads(signed.body())["expiresAfter"] == T0 + 30_000
    assert signed.action_hash() == "0x" + request().connection_id().hex()
    other = verified.generate_hyperliquid_agent(SAFE)
    with pytest.raises(ValueError, match="another key"):
        signing.verified(request(), other, signed.signature)
    with pytest.raises(PermissionError):
        keys.sign_hyperliquid_action(SAFE, "0x" + "ab" * 20, request().wire(), T0, T0 + 1)
    custody_keys = SignerAgentKeys(verified, SAFE)
    fresh = custody_keys.generate()
    assert custody_keys.held(frozenset({fresh, "0x" + "ab" * 20})) == {fresh}


class Substituting:
    address = LocalSigner.address

    def __init__(self, keys, forge):
        self.keys, self.forge = keys, forge

    def generate_hyperliquid_agent(self, account):
        return self.forge.get("address", self.keys.generate())

    def hyperliquid_agents(self, account, addresses):
        return self.forge.get("held", self.keys.held(addresses))

    def sign_hyperliquid_action(self, account, agent, action, nonce, expires_after):
        if "signature" in self.forge:
            return self.forge["signature"]
        return self.keys.sign_hyperliquid_action(
            account, agent, action, nonce + self.forge.get("nonce", 0), expires_after
        )


