def test_the_store_creates_its_table_and_document_in_one_transaction(tmp_path, funded):
    state = funded.store.load()
    store = TradingStore(tmp_path / "fresh.db")
    connect = store.connect

    class Stopped(sqlite3.Connection):
        def execute(self, sql, *args):
            if sql.startswith("INSERT"):
                raise RuntimeError("stopped before the first document")
            return super().execute(sql, *args)

    def stopped():
        uri = f"file:{store.path}?mode=rw"
        return sqlite3.connect(uri, uri=True, isolation_level=None, factory=Stopped)

    store.connect = stopped  # type: ignore[method-assign]
    with pytest.raises(RuntimeError):
        store.create(state)
    store.connect = connect  # type: ignore[method-assign]
    tables = sqlite3.connect(store.path).execute("SELECT name FROM sqlite_master").fetchall()
    assert tables == []


