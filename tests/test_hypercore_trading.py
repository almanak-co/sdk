def test_same_time_fills_whose_orders_disagree_on_ownership_halt():
    cloid = "0x" + "aa" * 16
    ours = (frozenset({cloid}), frozenset())
    book = Book(
        safe=SAFE,
        cursor=T0,
        cash=Decimal("10"),
        positions={"BTC": Decimal("0.001")},
        owned={"BTC": Decimal("0.001")},
    )
    # Two loops from 0.001 at one millisecond: an outside flatten and reopen, and a
    # strategy add then an outside trim. Either loop can run first.
    loops = [
        a_fill(1, T0 + 1, side="A", size="0.001", fee="0.0", start="0.001"),
        a_fill(2, T0 + 1, side="B", size="0.001", fee="0.0", start="0.0"),
        a_fill(3, T0 + 1, side="B", size="0.001", fee="0.0", start="0.001", cloid=cloid),
        a_fill(4, T0 + 1, side="A", size="0.001", fee="0.0", start="0.002"),
    ]
    for order in (loops, list(reversed(loops))):
        with pytest.raises(DataError, match="different owned exposure"):
            reconcile(book, pages(order, positions=[held("0.001")], value="10"), ours)
    # Ties whose orders agree, such as two outside loops, reconcile.
    outside = [loops[0], loops[1], {**loops[2], "tid": 5, "cloid": "0x" + "bb" * 16}, loops[3]]
    after = reconcile(book, pages(outside, positions=[held("0.001")], value="10"), ours)
    assert after.owned == {} and after.outside() == {"BTC": Decimal("0.001")}


