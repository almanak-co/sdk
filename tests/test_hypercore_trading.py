def retained(trader, planner):
    return trader.retain(planner)


def authority_for(trader, attempt, **changes):
    state = trader.state()
    authority = trader.authority(state, attempt)
    return authority.model_copy(update=changes)


def answer(result: InfoResult, value, received_at=None) -> InfoResult:
    return result.model_copy(
        update={"result": value, "received_at": received_at or result.received_at}
    )


def refused(funded, attempt, authority=None, now=None) -> str:
    state = funded.trader.state()
    authority = authority or funded.trader.authority(state, attempt)
    with pytest.raises(DataError) as error:
        admit(
            state.trading,
            state.custody.agents,
            attempt,
            authority,
            now or funded.run.now(),
            state.book,
        )
    assert error.value.kind == "authority"
    return str(error.value)


def trader_fills(funded, start, end):
    return funded.trader.observe(UserFillsByTime(user=SAFE, start_time=start, end_time=end))


def entry_attempt(funded, size=Decimal("0.001")):
    trader = funded.trader
    book = trader.observe(L2Book(coin="BTC"))
    now = funded.run.now()
    return retained(
        trader,
        lambda s: rules.plan_entry(s.trading, "BTC", trader.agent(s), True, size, book, now),
    )


def test_admission_refuses_an_unauthorized_agent_or_account(funded):
    attempt = entry_attempt(funded)
    base = funded.trader.authority(funded.trader.state(), attempt)
    role, agents, mode = base.role, base.agents, base.abstraction
    cases = {
        "does not report the agent": base.model_copy(
            update={"role": answer(role, {"role": "user"})}
        ),
        "read before the agent": base.model_copy(update={"role": answer(role, role.result, 1)}),
        "does not show": base.model_copy(update={"agents": answer(agents, [])}),
        "standard mode": base.model_copy(update={"abstraction": answer(mode, "default")}),
        "needs userRole": base.model_copy(update={"role": base.abstraction}),
    }
    for message, authority in cases.items():
        assert message in refused(funded, attempt, authority)
    ahead = attempt.request.model_copy(
        update={"nonce": attempt.request.nonce + signing.NONCE_FUTURE_MS}
    )
    assert "nonce window" in refused(funded, attempt.model_copy(update={"request": ahead}), base)
    stale = attempt.model_copy(update={"agent": "0x" + "ab" * 20})
    assert "current agent" in refused(funded, stale, base)
    signed = attempt.model_copy(update={"status": "signed"})
    assert "unsigned" in refused(funded, signed, base)


def test_admission_refuses_orders_outside_the_plan(funded):
    attempt = entry_attempt(funded)
    order = attempt.request.action.order
    base = funded.trader.authority(funded.trader.state(), attempt)

    def with_order(**fields):
        action = attempt.request.action.model_copy(
            update={"order": order.model_copy(update=fields)}
        )
        request = attempt.request.model_copy(update={"action": action})
        return attempt.model_copy(update={"request": request})

    assert "entry or reduce-only" in refused(funded, with_order(asset=1), base)
    assert "entry or reduce-only" in refused(funded, with_order(reduce_only=True), base)
    assert "slippage" in refused(funded, with_order(price=Decimal("90000")), base)
    old = attempt.book.model_copy(update={"received_at": attempt.book.received_at - 60_000})
    assert "age limit" in refused(funded, attempt.model_copy(update={"book": old}), base)
    assert "retained book" in refused(funded, attempt.model_copy(update={"book": None}), base)
    exit_attempt = with_order(reduce_only=True, is_buy=False).model_copy(update={"purpose": "exit"})
    assert "observed position" in refused(funded, exit_attempt, base)
    account = funded.trader.observe(ClearinghouseState(user=SAFE))
    flat = base.model_copy(update={"account": account})
    assert "fills up to its account snapshot" in refused(funded, exit_attempt, flat)
    cursor = funded.store.load().book.cursor
    fills = trader_fills(funded, cursor, typed(account).time)
    proven = flat.model_copy(update={"fills": fills})
    assert "strategy's own position" in refused(funded, exit_attempt, proven)
    default = answer(
        base.active, {**base.active.result, "leverage": {"type": "cross", "value": 20}}
    )
    assert "configured leverage" in refused(
        funded, attempt, base.model_copy(update={"active": default})
    )
    assert "observed leverage" in refused(funded, attempt, base.model_copy(update={"active": None}))
    book = attempt.book
    stale = answer(book, {**book.result, "time": book.result["time"] - 60_000})
    assert "age limit" in refused(funded, attempt.model_copy(update={"book": stale}), base)
    ahead = answer(book, {**book.result, "time": book.result["time"] + 5_000})
    assert "ahead of the clock" in refused(funded, attempt.model_copy(update={"book": ahead}), base)
    other = attempt.model_copy(update={"coin": "ETH"})
    assert "not a configured target" in refused(funded, other, base)


def test_admission_refuses_other_leverage_and_a_foreign_noop(funded):
    trader = funded.trader
    now = funded.run.now()
    attempt = retained(
        trader, lambda s: rules.plan_leverage(s.trading, "BTC", trader.agent(s), now)
    )
    base = trader.authority(trader.state(), attempt)
    action = attempt.request.action.model_copy(update={"leverage": 3})
    changed = attempt.model_copy(
        update={"request": attempt.request.model_copy(update={"action": action})}
    )
    assert "configured leverage" in refused(funded, changed, base)
    assert "observed position" in refused(
        funded, attempt, base.model_copy(update={"account": None})
    )
    holding = base.model_copy(update={"account": account_state([held("0.001")])})
    assert "no position" in refused(funded, attempt, holding)
    nonce = attempt.request.nonce + 1
    noop = signing.ActionRequest(action=signing.Noop(), nonce=nonce, expires_after=nonce + 1)
    foreign = attempt.model_copy(
        update={"request": noop, "purpose": "retire", "retires": attempt.id}
    )
    assert "own nonce" in refused(funded, foreign, base)


